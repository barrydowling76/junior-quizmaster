"""Build content.js + record every wizard clip.  usage: python3 gen_all.py OUT_DIR VOICE [--js-only]
VOICE: george | fable | santa | blend"""
import json, os, sys, subprocess, time, numpy as np, soundfile as sf
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import BANK, FACTS, CHEERS, OOPS, FEEDBACK, SCORE, QNUM, LINES
from names import NAMES, SAY, key

OUT, VOICE = sys.argv[1], sys.argv[2]
JS_ONLY = "--js-only" in sys.argv
AUD = os.path.join(OUT, "audio")
REVEAL_SAY = {"H2O": "H two O", "0": "zero", "1916": "nineteen sixteen", "J K Rowling": "J. K. Rowling"}

clips = []  # (path, text) in priority order
def add(p, t):
    if t: clips.append((p, t))
for k, t in LINES.items(): add(f"l/{k}", t)
for i, (a, b) in enumerate(CHEERS): add(f"c/{i}a", a); add(f"c/{i}b", b)
for i, (a, b) in enumerate(OOPS): add(f"o/{i}a", a); add(f"o/{i}b", b)
for i, t in enumerate(FEEDBACK): add(f"fb/{i}", t)
for i, t in enumerate(SCORE): add(f"sc/{i}", t)
for i, t in enumerate(QNUM): add(f"qn/{i}", t)
name_keys = []
for n in list(dict.fromkeys(NAMES + [k.title() for k in SAY])):
    k = key(n)
    if k in name_keys: continue
    name_keys.append(k); add(f"n/{k}", SAY.get(k, n) + "!")
bank_js = {}
for band, qs in BANK.items():
    bank_js[band] = []
    for i, q in enumerate(qs):
        text, ans = q[0], q[1]; alt = q[2] if len(q) > 2 else []
        bank_js[band].append({"q": text, "a": ans, "x": alt})
        add(f"q/{band}{i}", text)
        add(f"r/{band}{i}", f"The answer was {REVEAL_SAY.get(ans, ans)}.")
for i, t in enumerate(FACTS): add(f"f/{i}", t)

os.makedirs(OUT, exist_ok=True)
js = "// Generated by gen_all.py from content.py and names.py. Edit those, not this file.\n"
js += "const BANK = " + json.dumps(bank_js, ensure_ascii=False) + ";\n"
js += "const FACTS = " + json.dumps(FACTS, ensure_ascii=False) + ";\n"
js += "const CHEERS = " + json.dumps(CHEERS, ensure_ascii=False) + ";\n"
js += "const OOPS = " + json.dumps(OOPS, ensure_ascii=False) + ";\n"
js += "const FEEDBACK = " + json.dumps(FEEDBACK, ensure_ascii=False) + ";\n"
js += "const SCORE = " + json.dumps(SCORE, ensure_ascii=False) + ";\n"
js += "const QNUM = " + json.dumps(QNUM, ensure_ascii=False) + ";\n"
js += "const LINES = " + json.dumps(LINES, ensure_ascii=False) + ";\n"
js += "const VOICE_NAMES = new Set(" + json.dumps(name_keys) + ");\n"
open(os.path.join(OUT, "content.js"), "w").write(js)
json.dump([c[0] for c in clips], open(os.path.join(OUT, "..", "clips.json"), "w"))
print(f"{len(clips)} clips, {len(name_keys)} names, {sum(len(v) for v in BANK.values())} questions, {len(FACTS)} facts", flush=True)
if JS_ONLY: sys.exit()

from kokoro_onnx import Kokoro
D = os.path.dirname(os.path.abspath(__file__))
k = Kokoro(os.path.join(D, "tts/kokoro-fp32.onnx"), os.path.join(D, "tts/voices.bin"))
styles = {"george": "bm_george", "fable": "bm_fable", "santa": "am_santa"}
voice = styles.get(VOICE) or (0.6 * k.get_voice_style("bm_george") + 0.4 * k.get_voice_style("am_santa"))
speed = 0.9 if VOICE == "santa" else 0.88
FX = "asetrate=24000*0.89,aresample=24000,atempo=1.04,bass=g=3:f=180,treble=g=-2,aecho=0.8:0.6:35|70:0.18|0.08,volume=1.5,alimiter=limit=0.93"

def trim(s, sr, pad=0.06):
    thr = 0.02 * np.max(np.abs(s)) if len(s) else 0
    idx = np.where(np.abs(s) > thr)[0]
    if not len(idx): return s
    a, b = max(0, idx[0] - int(pad * sr)), min(len(s), idx[-1] + int(pad * 3 * sr))
    return s[a:b]

t0 = time.time(); done = 0
for i, (p, text) in enumerate(clips):
    dst = os.path.join(AUD, p + ".mp3")
    if os.path.exists(dst): continue
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    s, sr = k.create(text, voice=voice, speed=speed, lang="en-gb")
    tmp = dst[:-4] + ".wav"; sf.write(tmp, trim(s, sr), sr)
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", tmp, "-af", FX, "-ac", "1", "-b:a", "56k", dst], check=True)
    os.remove(tmp); done += 1
    if done % 10 == 0: print(f"{i+1}/{len(clips)}  {time.time()-t0:.0f}s  {p}", flush=True)
print("DONE", time.time() - t0, flush=True)
